    -- Split bundle_code string into array
    FOREACH
code IN ARRAY string_to_array(NEW.bundle_code, ',')
    LOOP
SELECT COUNT(*)
INTO exists_count
FROM bundle
WHERE data ->>'bundle_code' = trim (code);

IF
exists_count = 0 THEN
            RAISE EXCEPTION 'Invalid bundle code: %', code;
END IF;
END LOOP;

RETURN NEW;
END;
