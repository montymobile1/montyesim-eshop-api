    p_id         uuid    DEFAULT NULL,
    p_sort       text    DEFAULT 'created_at',
    p_dir        text    DEFAULT 'desc'
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
