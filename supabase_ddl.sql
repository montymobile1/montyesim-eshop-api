               'total', (SELECT count(*) FROM filtered),
               'facets', jsonb_build_object(
                   'all',    (SELECT count(*) FROM base),
                   'banned', (SELECT count(*) FROM base WHERE is_banned),
                   'active', (SELECT count(*) FROM base WHERE NOT is_banned)))
      INTO v_result;

    RETURN v_result;
END;
$$;

