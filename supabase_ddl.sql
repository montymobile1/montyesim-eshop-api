CREATE OR REPLACE FUNCTION public.admin_lock_group(p_group_id bigint)
RETURNS public.tag_group
LANGUAGE plpgsql
VOLATILE
SET search_path = public, pg_temp
AS $$
DECLARE
    v_group public.tag_group;
BEGIN
    IF p_group_id IS NULL THEN
